"""Shared paths and helpers for the SACLA manual builders.

Folder layout (relative to the project root, i.e. the folder holding build_all.py):

    resources/manuals/Offline/   resources/manuals/Online/    PDF manuals
    resources/examples/NNNN/readme.txt                         example readmes
    resources/web/                                             raw copy of the portal (wget)
    markdown/                                                  generated markdown
    html/                                                      generated html

Change a folder name here and every builder follows.
"""
import html
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESOURCES = ROOT / "resources"
MANUALS = RESOURCES / "manuals"
EXAMPLES = RESOURCES / "examples"
WEB = RESOURCES / "web"
MD = ROOT / "markdown"
HTML = ROOT / "html"

SITE = "http://xhpcfep.hpc.spring8.or.jp"
KINDS = ("Offline", "Online")

# Markdown page names (relative to MD). The html version uses the same names with .html.
PAGE = {
    "software": "SACLA_Software.md",
    "examples": "SACLA_Examples.md",
    "modules": "SACLA_Modules.md",
    "overview_offline": "SACLA_Overview_Offline.md",
    "overview_online": "SACLA_Overview_Online.md",
    "release": "SACLA_Release_History.md",
    "system": "SACLA_System.md",
}

# Web anchor -> PDF stem, used only when the portal's manual index page is not on disk
STEM_EXCEPTIONS = {
    "OfflineUDBWeb": "Offline-UDBWeb_UsersManual_en",
    "OnlineUDBWeb": "Online-UDBWeb_UsersManual_en",
    "RunDataViewer": "RunDataViewer_StartupGuide_en",
    "User-Database_Command_UserDatabaseAPI": "User-Database_Command_API_ReferenceGuide_en",
    "UserDatabaseAPIPythonIF": "UserDatabaseAPIPythonIF_StartupGuide_en",
    "CITIUSOnlineUserAPIPython": "CITIUSOnlineUserAPIPythonIF_UsersManual_en",
    "MPCCD_octal_image_assembly_algorithm": "MPCCD_octal_image_assembly_algorithm_ver1.1",
}


def rel(target, from_file):
    """Relative link from the file `from_file` to `target` (both Paths), with / separators."""
    return Path(os.path.relpath(target, Path(from_file).parent)).as_posix()


def md_link(text, target):
    return f"[{text}](<{target}>)"


def read(path):
    path = Path(path)
    return path.read_text(encoding="utf-8", errors="replace") if path.is_file() else ""


def strip_tags(s):
    return html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", s))).strip()


def write(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


_INDEX = {}


def manual_index(kind):
    """{anchor: {"stem": pdf stem, "title": ..., "text": description}} from the portal's
    manual index page (resources/web/manuals/<kind>/index.html)."""
    kind = kind.lower()
    if kind not in _INDEX:
        t = read(WEB / "manuals" / kind / "index.html")
        found = {}
        for block in re.split(r'(?=<div id="[^"]+" class="jumpable">)', t)[1:]:
            anchor = re.match(r'<div id="([^"]+)"', block).group(1)
            pdf = re.search(r'href="[^"]*/([^"/]+)\.pdf"', block)
            head = re.search(r'card-header[^>]*>(.*?)</div>', block, re.S)
            para = re.search(r"<p>(.*?)</p>", block, re.S)
            found[anchor] = {
                "stem": pdf.group(1) if pdf else None,
                "title": strip_tags(head.group(1)) if head else anchor,
                "text": strip_tags(para.group(1)) if para else "",
            }
        _INDEX[kind] = found
    return _INDEX[kind]


def manual_pdf(kind, anchor):
    """Path of the local PDF for a web anchor (e.g. 'Offline', 'DataConvert4'), or None."""
    kind = kind.capitalize()
    info = manual_index(kind).get(anchor) or {}
    stem = info.get("stem") or STEM_EXCEPTIONS.get(anchor, f"{anchor}_UsersManual_en")
    for k in (kind, *KINDS):          # e.g. MPCCD algorithm is only in Offline
        p = MANUALS / k / f"{stem}.pdf"
        if p.is_file():
            return p
    return None


def manual_description(kind, anchor):
    return (manual_index(kind).get(anchor) or {}).get("text", "")


def manual_by_name(kind, name):
    """Local PDF whose file name starts with `name_` (used for release-history entries)."""
    for p in sorted((MANUALS / kind.capitalize()).glob(f"{name}_*.pdf")):
        return p
    return None


def header(title, source_url, builder, back=None, from_file=None):
    """Standard page header used by all builders."""
    lines = [f"# {title}", "",
             f"Recreated from <{source_url}> (VPN only).  ",
             f"Generated by `src/{builder}` – rebuild with `python3 build_all.py`.", ""]
    if back:
        text, target = back
        lines += [f"[← {text}](<{rel(target, from_file)}>)", ""]
    return lines
